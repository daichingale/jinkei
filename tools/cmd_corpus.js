// 複合命令（2〜3 文）: 選ぶ → 動かす/並べる … の連結。正解は意図のリスト
const SEL_STEPS = ['select', 'select_all'];
const NEXT_STEPS = ['move', 'rotate', 'scale', 'arrange_circle', 'arrange_line', 'arrange_block', 'flip', 'face', 'pose'];
const CONNECTORS = {train: ['、それから', '、', '、そして', '、次に'], dev: ['、そのあと', '、続けて', '、その後'], held: ['、さらに', '、つぎに', '、そのうえで', '、あとは']};
function genCompound(R, kind, ctx) {
  const held = kind === 'held', k = KIND[kind];
  const a = pick(R, SEL_STEPS);
  let b = pick(R, NEXT_STEPS);
  const ga = genOne(R, a, kind, ctx, 0), gb = genOne(R, b, kind, ctx, 0, true);
  const sa = ga.text.replace(/(?:て|で|る|ます|ください)$/, m => m), sb = gb.text;
  const con = pick(R, CONNECTORS[kind]);
  const sa2 = /^から|^て、$/.test(con) ? sa : sa;
  void k; void held;
  return {text: sa2 + con + sb, steps: [{intent: a, args: ga.args}, {intent: b, args: gb.args}], ctx};
}
function genOne(R, intent, kind, ctx, level, noTarget) {
  const k = KIND[kind], held = kind === 'held';
  let tpls = TPL[intent][k];
  if (noTarget) { const t2 = tpls.filter(t => !/\{(T|S|I|RG)[\/}]/.test(t)); if (t2.length) tpls = t2; else tpls = tpls.map(t => t.replace(/\{T\/[^}]+\}/g, '').replace(/\{T\}/g, '')); }
  const tpl = pick(R, tpls);
  const {text, gold} = expandTpl(R, tpl, ctx, held, intent);
  return {text: level ? noise(R, text, level, held) : text, args: goldArgs(intent, gold, ctx, noTarget)};
}
// 正解の args（取り出し規則の出力と比べる）。テンプレートに出てこなかった値は「無い」ことが正解
function goldArgs(intent, g, ctx, noTarget) {
  const o = {};
  const keys = {move: ['target', 'dirs', 'amount'], rotate: ['target', 'deg', 'cw'], scale: ['target'], spacing: ['target', 'value'], flip: ['target'], swap: ['a', 'b'], face: ['target', 'value'], pose: ['target', 'value'], carry: ['target', 'value'], step_style: ['target', 'value'], action: ['target', 'value'],
    set_goto: ['to'], tempo: ['value'], grid: ['mode'], snap: ['value'], tool: ['tool'], add_members: ['target', 'count'], set_bulk: ['counts'], set_split: ['at'], set_cut: ['at'], set_counts: ['value'], set_hold: ['value'],
    select: ['target'], move_to: ['target'], unpin: ['target'], delete_members: ['target'], duplicate_members: ['target'], copy_members: ['target'], cut_members: ['target']};
  const ks = keys[intent] || (intent.startsWith('arrange_') ? ['target'] : []);
  for (const k of ks) { if (k in g) o[k] = g[k]; else if (k === 'target') o[k] = null; }
  if (noTarget && 'target' in o) o.target = null;
  if (intent === 'set_add' && g.counts != null) o.counts = g.counts;
  if (intent === 'set_hold' && !('value' in o)) o.value = {abs: 0};
  if (intent === 'scale' && g.factor != null) o.factor = g.factor;
  if (intent === 'set_bulk') { if (Array.isArray(g.counts)) o.counts = g.counts; else if (g._k) o.counts = Array(g._k).fill(g.counts); }
  if (intent === 'arrange_block' && g.cols != null) o.cols = g.cols;
  if (intent === 'set_counts' && !('value' in o) && g.counts != null) o.value = {abs: g.counts};
  return o;
}
function genNone(R, kind, level) { const k = KIND[kind]; let s = pick(R, NONE_TPL[k]); if (s === '歩' || s === '前' || s === '3') s = pick(R, ['ありがとう', 'うーん', 'こんにちは']); return {text: level ? noise(R, s, level * 0.5, kind === 'held') : s}; }
// 全部の意図が同じくらい出るように回す。n: 合計件数。noneRate: none の割合。compoundRate: 複合の割合
function genSet(kind, seed, n, o) {
  o = o || {};
  const R = rngOf(seed * 7919 + KIND[kind] * 104729 + 17), out = [];
  const intents = Object.keys(TPL), level = o.level == null ? (kind === 'train' ? 1.0 : 0.8) : o.level;
  const noneRate = o.noneRate == null ? 0.05 : o.noneRate, compRate = o.compoundRate == null ? 0.05 : o.compoundRate;
  for (let i = 0; i < n; i++) {
    const ctx = genCtx(R, kind === 'held');
    const r = R();
    if (r < noneRate) { const g = genNone(R, kind, level); out.push({text: g.text, intent: 'none', args: {}, ctx}); continue; }
    if (r < noneRate + compRate) { const g = genCompound(R, kind, ctx); g.text = noise(R, g.text, level * 0.6, kind === 'held'); out.push({text: g.text, intent: 'compound', steps: g.steps, ctx}); continue; }
    const intent = intents[i % intents.length];
    const g = genOne(R, intent, kind, ctx, level);
    out.push({text: g.text, intent, args: g.args, ctx});
  }
  return out;
}
