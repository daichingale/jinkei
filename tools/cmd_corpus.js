function tgt(R, ctx, kind, held) {   // 対象 → {tx, v: target}
  const secs = ctx.sections, si = Math.floor(R() * secs.length), s = secs[si], r = R();
  const mem = ctx.members.filter(m => m.sec === si), m = pick(R, mem);
  const regionsA = [['前の列', 'front-row'], ['後ろの列', 'back-row'], ['左半分', 'left-half'], ['右半分', 'right-half'], ['真ん中', 'center'], ['前半分', 'front-half']];
  const regionsH = [['最前列', 'front-row'], ['一番前の人', 'front-row'], ['左側の人', 'left-half'], ['右側の人', 'right-half'], ['中央の人', 'center'], ['最後列', 'back-row'], ['左端', 'left-end'], ['右端', 'right-end'], ['奥の列', 'back-row']];
  const allA = ['全員', 'みんな', '全体', '全部'], allH = ['全メンバー', 'みなさん', '全員の', '全て', 'オール'];
  const selA = ['選んだ人', 'それ', '選択中の人', 'この人たち', 'その人たち'], selH = ['さっき選んだ人', '選択している人', '今選んでる人', 'いま選んだ人たち'];
  if (kind === 'any' && r < 0.2) return {tx: '', v: null};
  if (kind === 'sec') { if (r < 0.7) return {tx: held ? pick(R, [s.label, s.label + 'パート', s.label + 'の人たち', s.id]) : pick(R, [s.label, s.label + 'の人', s.id, s.label + 'パート']), v: {secs: [si]}}; const s2i = (si + 1) % secs.length; return {tx: held ? `${s.label}と${secs[s2i].label}` : `${s.label}と${secs[s2i].label}`, v: {secs: [si, s2i]}}; }
  if (kind === 'ids') return r < 0.5 ? {tx: m.id, v: {ids: [m.id]}} : r < 0.8 ? {tx: `${s.label}${m.id.slice(s.id.length)}番`, v: {ids: [m.id]}} : (() => { const m2 = mem.find(x => x.id !== m.id) || m; return {tx: held ? `${m.id}と${m2.id}` : `${m.id}、${m2.id}`, v: {ids: m.id === m2.id ? [m.id] : [m.id, m2.id]}}; })();
  if (kind === 'sec1') return {tx: secName(R, s, held), v: {secs: [si]}};
  const q = R(), sx = q < 0.35 ? 'sec' : q < 0.5 ? 'all' : q < 0.65 ? 'sel' : q < 0.75 ? 'region' : q < 0.83 ? 'ids' : q < 0.9 ? 'secregion' : 'empty';
  if (sx === 'sec') return {tx: held ? pick(R, [s.label, s.label + 'パート', s.label + 'の子たち', s.id]) : pick(R, [s.label, s.label + 'の人', s.id, s.label + 'パート', s.label + 'の人たち']), v: {secs: [si]}};
  if (sx === 'all') return {tx: pick(R, held ? allH : allA), v: {all: true}};
  if (sx === 'sel') return {tx: pick(R, held ? selH : selA), v: {sel: true}};
  if (sx === 'empty') return {tx: '', v: null};
  if (sx === 'region') { const g = pick(R, held ? regionsH : regionsA); return {tx: g[0], v: {region: g[1]}}; }
  if (sx === 'ids') return {tx: m.id, v: {ids: [m.id]}};
  const g = pick(R, held ? regionsH.filter(x => /最前|最後|奥/.test(x[0])) : regionsA.slice(0, 2)); return {tx: `${s.label}の${g[0]}`, v: {secs: [si], region: g[1]}};
}
