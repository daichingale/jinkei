const SEC_HELD = [['ta', 'Aチーム'], ['tc', 'Bチーム'], ['yr', '1年生'], ['nw', '新入部員'], ['pa', 'パート1']];
function genCtx(R, held) {
  const pool = SEC_POOL.concat(held && chance(R, 0.5) ? SEC_HELD : []);
  const k = 2 + Math.floor(R() * 4), chosen = [];
  while (chosen.length < k) { const s = pick(R, pool); if (!chosen.includes(s)) chosen.push(s); }
  const sections = chosen.map(([id, label]) => ({id, label, n: 3 + Math.floor(R() * 6)}));
  const members = [];
  sections.forEach((s, si) => { for (let i = 1; i <= s.n; i++) members.push({id: s.id + i, sec: si, x: Math.round(((i - 1) * 1.25 - (s.n - 1) * 0.625 + (R() - .5) * .2) * 100) / 100, y: Math.round((si * 2.5 - 3 + (R() - .5) * .2) * 100) / 100}); });
  const nsets = 2 + Math.floor(R() * 5), sets = []; for (let i = 1; i <= nsets; i++) sets.push(String(i));
  if (chance(R, 0.2)) sets.splice(1, 0, '1A');
  let sel = [];
  if (chance(R, 0.7)) { const si = Math.floor(R() * sections.length); sel = members.filter(m => m.sec === si).map(m => m.id); if (chance(R, 0.4)) sel = sel.slice(0, 2 + Math.floor(R() * 3)); }
  return {sections, members, sets, sel, curSet: Math.floor(R() * sets.length), field: {type: 'gym'}, stride: 0.625, beatsPerBar: 4};
}

