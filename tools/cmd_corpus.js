const PARTICLES_DROP = /[をにへが]$/;
function expandTpl(R, tpl, ctx, held, intent) {
  let gold = {}, text = tpl;
  // (a|b|c) と [x]
  text = text.replace(/\(([^()]*?)\)(\?)?/g, (m, body, q) => { if (q && chance(R, 0.5)) return ''; return pick(R, body.split('|')); });
  text = text.replace(/\[([^\[\]]*?)\]/g, (m, body) => { if (!chance(R, 0.5)) return ''; const alts = body.split('|'); return pick(R, alts); });
  let rotMemo = null;
  text = text.replace(/\{([A-Z0-9]+)(?:\/([^}]+))?\}/g, (m, name, part) => {
    let v;
    if (name === 'ROTW' || name === 'DT') { rotMemo = rotMemo || rot(R, held); return name === 'ROTW' ? rotMemo.w : rotMemo.dt; }
    if (name === 'ROT') { rotMemo = rot(R, held); Object.assign(gold, {cw: rotMemo.v.cw, deg: rotMemo.v.deg}); return rotMemo.tx; }
    if (name === 'SCLS') return '';
    v = SLOT[name](R, ctx, held);
    if (name === 'SCL') { Object.assign(gold, v.v); return v.tx; }
    if (name === 'T' || name === 'S' || name === 'I' || name === 'RG') { const key = intent === 'swap' ? 'a' : 'target'; gold[key] = v.v && v.v.region && name === 'RG' ? {region: v.v.region} : v.v; }
    else Object.assign(gold, v.v);
    let tx = v.tx;
    if (part && tx) tx = tx + (chance(R, 0.12) ? '' : part); else if (part) tx = '';
    return tx;
  });
  return {text, gold};
}

