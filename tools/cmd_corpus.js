const KANA = [['選んで', 'えらんで'], ['選ぶ', 'えらぶ'], ['選択', 'せんたく'], ['動かして', 'うごかして'], ['移動', 'いどう'], ['全員', 'ぜんいん'], ['後ろ', 'うしろ'], ['右', 'みぎ'], ['左', 'ひだり'], ['客席', 'きゃくせき'], ['回して', 'まわして'], ['並べて', 'ならべて'], ['広げて', 'ひろげて'], ['追加', 'ついか'], ['削除', 'さくじょ'], ['保存', 'ほぞん'], ['再生', 'さいせい'], ['戻して', 'もどして'], ['直して', 'なおして'], ['次の', 'つぎの'], ['前', 'まえ'], ['円', 'えん'], ['奥', 'おく'], ['歩', 'ほ'], ['拍', 'はく'], ['反転', 'はんてん'], ['入れ替え', 'いれかえ'], ['向き', 'むき'], ['姿勢', 'しせい'], ['停止', 'ていし'], ['印刷', 'いんさつ'], ['動画', 'どうが'], ['間隔', 'かんかく']];
const TAILS = ['お願いします', 'ください', 'お願い', 'ね', 'よ', 'ちょっと', 'です', 'ます', 'かな', 'ほしい', '！', '。', '…', 'っす'];
const HEADS = ['えっと', 'あの', 'じゃあ', 'まず', 'とりあえず', 'はい', 'ねえ', 'すみません', 'あのー', 'ええと', 'それじゃ', 'で、', 'じゃ'];
function noise(R, s, level, held) {
  // 表記ゆれ（漢字→かな）
  if (chance(R, 0.18 * level)) for (const [a, b] of KANA) if (s.includes(a) && chance(R, 0.5)) s = s.split(a).join(b);
  // カタカナ→ひらがな（ふつうの打ち方・音声認識のゆれ）
  if (chance(R, 0.08 * level)) s = s.replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));
  // 助詞の脱落
  if (chance(R, 0.22 * level)) { const ps = ['を', 'に', 'へ', 'が']; for (const p of ps) { const k = s.indexOf(p); if (k > 0 && chance(R, 0.4)) { s = s.slice(0, k) + s.slice(k + 1); break; } } }
  // 誤字（入れ替え・脱落・重複）。数字は壊さない
  if (chance(R, 0.08 * level) && s.length > 4) { const i = 1 + Math.floor(R() * (s.length - 2)); const bad = ch => /[0-9０-９a-zA-Z〇一二三四五六七八九十]/.test(ch || ''); if (!bad(s[i]) && !bad(s[i + 1]) && !bad(s[i - 1])) { const k = R(); s = k < 0.4 ? s.slice(0, i) + s[i + 1] + s[i] + s.slice(i + 2) : k < 0.75 ? s.slice(0, i) + s.slice(i + 1) : s.slice(0, i) + s[i] + s.slice(i); } }
  // 音声認識のような区切りの空白
  if (chance(R, 0.18 * level)) s = s.replace(/([をにへでがは])/g, (m, p) => chance(R, 0.55) ? p + ' ' : p).trim();
  else if (chance(R, 0.05 * level)) s = s.split('').map(ch => chance(R, 0.15) ? ch + ' ' : ch).join('').trim();
  // 前置き・語尾
  if (chance(R, 0.14 * level)) s = pick(R, HEADS) + (chance(R, 0.4) ? '、' : '') + s;
  if (chance(R, 0.28 * level)) s = s + pick(R, TAILS);
  if (held && chance(R, 0.06)) s = s.replace(/ください$/, 'くださいー');
  return s;
}

